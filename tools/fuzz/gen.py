    def s_for(self, ind, depth):
        r = self.r
        c = r.randint(0, 5)
        saved_frozen = set(self.frozen)
        x = self.fresh()
        if c == 0:
            k, it = 'int', self.iterable('range', 1)
        elif c == 1:
            src = self.expr(self.pick(['list', 'tuple', 'str', 'bytes', 'set']), 1)
            k = ELEM[self.kind_last_iter(src)]
            it = src
        elif c == 2:
            y = self.fresh()
            seqk = self.pick(['list', 'str', 'tuple'])
            it = 'enumerate(%s)' % self.expr(seqk, 1)
            self.emit(ind, 'for %s, %s in %s:' % (y, x, it))
            self.scope[y], self.scope[x] = 'int', ELEM[seqk]
            return self.loop_body(ind, depth, x, saved_frozen, extra=y)
        elif c == 3:
            y = self.fresh()
            dd = self.expr('dict', 1)
            self.emit(ind, 'for %s, %s in %s.items():' % (x, y, dd))
            if dd in self.scope:
                self.frozen.add(dd)
            self.scope[x], self.scope[y] = 'str', 'num'
            return self.loop_body(ind, depth, x, saved_frozen, extra=y)
        elif c == 4:
            y = self.fresh()
            self.emit(ind, 'for %s, %s in zip(%s, %s):' % (x, y, self.expr('list', 1), self.expr('str', 1)))
            self.scope[x], self.scope[y] = 'num', 'str'
            return self.loop_body(ind, depth, x, saved_frozen, extra=y)
        else:
            k, it = 'num', 'reversed(%s)' % self.expr(self.pick(['list', 'tuple']), 1)
        if it in self.scope:
            self.frozen.add(it)
        self.emit(ind, 'for %s in %s:' % (x, it))
        self.scope[x] = k
        self.loop_body(ind, depth, x, saved_frozen)

    def kind_last_iter(self, src):
        if src in self.scope:
            return self.scope[src]
        if src.startswith(('b', "b'")) or 'bytes' in src or '.encode' in src:
            return 'bytes'
        return 'list'

    def loop_body(self, ind, depth, x, saved_frozen, extra=None):
        # loop variables are rebound by the loop, and what the loop iterates
        # over must not grow: neither is stored to or mutated inside it
        self.frozen.update(n for n in re.findall(r'[A-Za-z_]\w*', self.lines[-1]) if n in self.scope)
        self.frozen.add(x)
        if extra:
            self.frozen.add(extra)
        self.block(ind + 1, self.r.randint(1, 3), depth - 1, in_loop=True)
        self.loop_tail(ind, depth)
        self.frozen = saved_frozen
        self.scope.pop(x, None)
        if extra:
            self.scope.pop(extra, None)
        if self.chance(0.3):
            self.emit(ind, 'else:')
            self.block(ind + 1, 1, depth - 1)

