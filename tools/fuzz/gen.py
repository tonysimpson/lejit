"""Random, valid, deterministic Python 3.7 programs for the differential
fuzzer (doc/BUILD.md, Fuzzing). The same seed gives the same program.

    python3 tools/fuzz/gen.py SEED          # print the program

Expressions are generated by kind, so most of them run without raising:
  num   int, float, bool or bigint (NaN, inf, -0.0, 2**31, 2**63 ...)
  int   int, bool or bigint
  str, bytes
  list, tuple, set   of nums
  dict  str -> num
  obj   an instance of one of the program's classes (fields a, b: num)
  any   any of these; read through isinstance tests that narrow it
Growth is bounded: `*`, `**` and `<<` take a literal on the right, and a
sequence built by concatenation is cut to a few items when stored.
Nothing reads ids, object hashes, time or run-time randomness, and nothing
prints from a finaliser (a generator's finally, __del__): when one runs
is C18 and C56.
"""
import random
import re
import sys

NUM_LITS = ['0', '1', '-1', '2', '3', '7', '-5', '255', '256', '1000003',
            '2**31-1', '2**31', '-2**31', '2**32', '2**63-1', '2**63',
            '-2**63', '-2**63-1', '2**64', '10**20', '-10**18', '0.0',
            '-0.0', '0.5', '1.5', '-2.25', '1e16', '1e308', '5e-324',
            'nan', 'inf', '-inf', 'True', 'False', '3.0', '-7.5']
INT_LITS = ['0', '1', '-1', '2', '3', '7', '-5', '255', '256', '1000003',
            '2**31-1', '2**31', '-2**31', '2**32', '2**63-1', '2**63',
            '-2**63', '2**64', '10**20', 'True', 'False', '-9']
SMALL = ['0', '1', '2', '3']
STR_LITS = ["''", "'a'", "'abc'", "'xyz'", "'Hello'", "'a,b,c'", "'  pad '",
            "'\\u00e9t\\u00e9'", "'12'", "'-3'", "'aAbB'"]
BYTES_LITS = ["b''", "b'a'", "b'abc'", "b'\\x00\\xff'", "b'xyz'"]
KEYS = ["'k0'", "'k1'", "'k2'", "'a'", "'b'"]
EXC = ['ZeroDivisionError', 'IndexError', 'KeyError', 'TypeError',
       'ValueError', 'OverflowError', 'AttributeError', 'ArithmeticError',
       'LookupError', 'Exception']
CONSTS = {'num': NUM_LITS, 'int': INT_LITS, 'str': STR_LITS,
          'bytes': BYTES_LITS}
KINDS = ['num', 'int', 'str', 'bytes', 'list', 'tuple', 'set', 'dict', 'obj']
SEQS = ('str', 'bytes', 'list', 'tuple')
ELEM = {'list': 'num', 'tuple': 'num', 'set': 'num', 'str': 'str',
        'bytes': 'int', 'dict': 'str', 'range': 'int'}
ISINST = {'int': 'int', 'num': '(int, float)', 'str': 'str',
          'bytes': 'bytes', 'list': 'list', 'tuple': 'tuple', 'set': 'set',
          'dict': 'dict'}


class Func:
    def __init__(self, name, params, ret, gen=False):
        self.name, self.params, self.ret, self.gen = name, params, ret, gen
        # params: (name, kind, default or None, is_kwonly)


class Gen:
    def __init__(self, seed):
        self.r = random.Random(seed)
        self.n = 0
        self.lines = []
        self.funcs = []          # module-level functions callable so far
        self.classes = []        # (name, has_setter, slots)
        self.consts = {}         # kind -> names of module-level constants

    # ---- helpers ------------------------------------------------------

    def fresh(self, p='v'):
        self.n += 1
        return '%s%d' % (p, self.n)

    def chance(self, p):
        return self.r.random() < p

    def pick(self, xs):
        return self.r.choice(xs)

    def emit(self, ind, s):
        self.lines.append('    ' * ind + s)

    def vars_of(self, kind):
        return [v for v, k in self.scope.items() if k == kind or
                (kind == 'num' and k == 'int')]

    # ---- expressions --------------------------------------------------

    def expr(self, kind, d=3):
        if kind == 'any':
            kind = self.pick(KINDS if self.classes else KINDS[:-1])
        vs = self.vars_of(kind)
        if vs and (d <= 0 or self.chance(0.35)):
            return self.pick(vs)
        if d <= 0:
            return self.lit(kind)
        return getattr(self, 'e_' + kind)(d - 1)

    def lit(self, kind):
        r = self.r
        if kind in CONSTS and self.consts.get(kind) and self.chance(0.25):
            return self.pick(self.consts[kind])
        if kind == 'num':
            return self.pick(NUM_LITS)
        if kind == 'int':
            return self.pick(INT_LITS)
        if kind == 'str':
            return self.pick(STR_LITS)
        if kind == 'bytes':
            return self.pick(BYTES_LITS)
        if kind == 'list':
            return '[%s]' % ', '.join(self.pick(NUM_LITS) for _ in range(r.randint(0, 4)))
        if kind == 'tuple':
            n = r.randint(0, 4)
            return '(%s%s)' % (', '.join(self.pick(NUM_LITS) for _ in range(n)), ',' if n == 1 else '')
        if kind == 'set':
            return '{%s}' % ', '.join(self.pick(INT_LITS) for _ in range(r.randint(1, 4)))
        if kind == 'dict':
            return '{%s}' % ', '.join('%s: %s' % (k, self.pick(NUM_LITS))
                                      for k in r.sample(KEYS, r.randint(0, 3)))
        if kind == 'obj' and not self.classes:
            return self.lit('num')
        if kind == 'obj':
            c = self.pick(self.classes)[0]
            return '%s(%s, %s)' % (c, self.pick(NUM_LITS), self.pick(NUM_LITS))
        raise ValueError(kind)

    def idx(self, seq, elem, d):
        """an index into seq: safe (wrapped) or not"""
        i = self.expr('int', d)
        if self.chance(0.2):
            # the index is the length the bounds check reads, or near it
            i = self.pick(['len(%s)', 'len(%s) - 1', '-len(%s)', 'len(%s) + 1', '~len(%s)',
                           '-len(%s) - 1', 'len(%s) // 2']).replace('%s', seq)
            if self.chance(0.5):
                return '(%s)[%s]' % (seq, i)
            return '((%s)[%s] if %s else %s)' % (seq, i, seq, self.lit(elem))
        if self.chance(0.7):
            return '((%s)[%s %% len(%s)] if %s else %s)' % (seq, i, seq, seq, self.lit(elem))
        return '(%s)[%s]' % (seq, i)

    def comp(self, kind, body_kind, d, brackets):
        """a comprehension over a sequence: [body for x in it if cond]"""
        itk = self.pick(['list', 'tuple', 'str', 'bytes', 'range', 'dict', 'set'])
        it = self.iterable(itk, d)
        x = self.fresh('c')
        saved = dict(self.scope)
        self.scope[x] = ELEM[itk]
        body = self.expr(body_kind, d)
        if brackets == '{:}':
            body = '%s: %s' % (self.e_str(0) if self.chance(0.5) else 'str(%s)' % x,
                               body)
            brackets = '{}'
        cond = (' if %s' % self.cond(d)) if self.chance(0.4) else ''
        self.scope = saved
        return '%s%s for %s in %s%s%s' % (brackets[0], body, x, it, cond, brackets[1])

    def iterable(self, itk, d):
        if itk == 'range':
            return self.pick(['range(%d)' % self.r.randint(0, 6),
                              'range(%d, %d)' % (self.r.randint(-3, 3), self.r.randint(0, 6)),
                              'range(%d, %d, -1)' % (self.r.randint(3, 6), self.r.randint(-2, 2)),
                              'range(len(%s))' % self.expr(self.pick(SEQS), d)])
        if itk == 'dict' and self.chance(0.3):
            return self.expr('dict', d)   # keys; items() is in for loops
        return self.expr(itk, d)

    def e_num(self, d):
        r = self.r
        e = lambda k='num': self.expr(k, d)
        c = r.randint(0, 27)
        if c < 5:
            return self.divide(e(), self.pick(['+', '-', '+', '-', '/', '//', '%']), e())
        if c < 7:
            return '(%s * %s)' % (e(), self.pick(NUM_LITS))
        if c == 7:
            return '(%s ** %s)' % (e(), self.pick(['0', '1', '2', '-1', '0.5']))
        if c == 8:
            return '(-%s)' % e()
        if c == 9:
            return '%s(%s)' % (self.pick(['abs', 'float', 'int', 'round', 'bool']), e())
        if c == 10:
            return '%s(%s, %s)' % (self.pick(['min', 'max']), e(), e())
        if c == 11:
            return 'len(%s)' % self.expr(self.pick(SEQS + ('set', 'dict')), d)
        if c == 12:
            return 'sum(%s)' % self.expr(self.pick(['list', 'tuple', 'set']), d)
        if c == 13:
            return '(%s if %s else %s)' % (e(), self.cond(d), e())
        if c == 14 and self.classes:
            o = self.expr('obj', d)
            return self.pick(['%s.a' % o, '%s.b' % o, '%s.p' % o, '%s.m(%s)' % (o, e()),
                              'len(%s)' % o, '%s[%s]' % (o, self.pick(SMALL + ['-1', '5'])),
                              '%s(%s)' % (o, e()), '%s.scale' % o, 'sum(%s)' % o,
                              '%s.twice(%s)' % (o, e())])
        if c == 15:
            return self.idx(self.expr(self.pick(['list', 'tuple']), d), 'num', d)
        if c == 16:
            return 'math.%s(%s)' % (self.pick(['floor', 'ceil', 'sqrt', 'fabs', 'trunc', 'exp', 'log1p']), e())
        if c == 17:
            return self.e_int(d)
        if c == 18:
            return '%s(%s, %s)' % (self.pick(['min', 'max']), self.expr('list', d),
                                   self.pick(['default=0', 'default=-1.5']))
        if c == 19:
            dct = self.expr('dict', d)
            return self.pick(['%s.get(%s, %s)' % (dct, self.pick(KEYS), e())] * 3 +
                             ['%s[%s]' % (dct, self.pick(KEYS))])
        if c == 20:
            return 'sum(%s)' % self.comp('num', 'num', d, '()')
        if c == 21:
            return self.call_expr('num', d)
        if c == 22:
            return 'math.copysign(%s, %s)' % (e(), e())
        if c == 23:
            return '%s(%s%s)' % (self.pick(['max', 'min']), self.comp('num', 'num', d, '[]'),
                                 self.pick(['', ', default=%s' % self.pick(NUM_LITS)]))
        if c == 24:
            return '(%s %s %s)' % (e(), self.pick(['<', '<=', '==', '!=', '>', '>=']), e())
        if c == 25:
            if self.chance(0.5):
                return '%s(%s)' % (self.pick(['float', 'int']), self.pick(
                    ["'nan'", "'-inf'", "'1e3'", "'-0.0'", "'2.5'", "'17'", "' -3 '", "'0x1f'"]))
            return self.pick(['round(%s, %s)' % (e(), self.pick(['0', '1', '-1', '2'])),
                              'int(%s).bit_length()' % e(),
                              '%s(%s, key=%s)' % (self.pick(['min', 'max']), self.expr('list', d),
                                                  self.pick(['abs', 'lambda q: -q', 'str']))])
        return '(%s %s %s)' % (e(), self.pick(['+', '-', '*']), self.pick(NUM_LITS))

    def divide(self, a, op, b):
        """a op b, a divisor that is mostly not zero"""
        if op in ('/', '//', '%') and self.chance(0.6):
            b = '(%s or %s)' % (b, self.pick(['3', '-7', '2**63', '0.5']))
        return '(%s %s %s)' % (a, op, b)

    def e_int(self, d):
        e = lambda k='int': self.expr(k, d)
        c = self.r.randint(0, 14)
        if c < 4:
            return self.divide(e(), self.pick(['+', '-', '//', '%', '&', '|', '^']), e())
        if c == 4:
            return '(%s %s %d)' % (e(), self.pick(['<<', '>>']), self.r.choice([0, 1, 3, 31, 32, 63, 64, 65]))
        if c == 5:
            return '(~%s)' % e()
        if c == 6:
            return 'divmod(%s, %s)[%d]' % (e(), e(), self.r.randint(0, 1))
        if c == 7:
            return 'len(%s)' % self.expr(self.pick(SEQS), d)
        if c == 8:
            return 'int(%s)' % self.expr('num', d)
        if c == 9:
            return '(%s * %s)' % (e(), self.pick(INT_LITS))
        if c == 10:
            s = self.expr('str', d)
            return self.pick(['%s.count(%s)' % (s, self.pick(STR_LITS)),
                              '%s.find(%s)' % (s, self.pick(STR_LITS)),
                              '(ord(%s[0]) if %s else -1)' % (s, s)])
        if c == 11:
            return self.idx(self.expr('bytes', d), 'int', d)
        if c == 12:
            return 'hash(%s)' % self.pick([e(), self.expr('num', d), self.expr('tuple', d)])
        if c == 13:
            return self.call_expr('int', d)
        return 'pow(%s, %s, %s)' % (e(), self.pick(SMALL), self.pick(['7', '2**61-1', '1000003']))

    def e_str(self, d):
        e = lambda k='str': self.expr(k, d)
        c = self.r.randint(0, 15)
        if c < 2:
            self.grow = True
            return '(%s + %s)' % (e(), e())
        if c == 2:
            self.grow = True
            return '(%s * %s)' % (e(), self.pick(SMALL + ['-1']))
        if c == 3:
            return '%s[%s:%s]' % (e(), self.slice_bound(d), self.slice_bound(d))
        if c == 4:
            return '%s.%s()' % (e(), self.pick(['upper', 'lower', 'strip', 'title', 'swapcase']))
        if c == 5:
            return '%s(%s)' % (self.pick(['str', 'repr']), self.expr(self.pick(['num', 'int', 'tuple', 'list']), d))
        if c == 6:
            return "'%%s|%%r' %% (%s, %s)" % (e(), self.expr('num', d))
        if c == 7:
            return "'{}:{}'.format(%s, %s)" % (e(), self.expr('num', d))
        if c == 8:
            return "','.join(str(x) for x in %s)" % self.expr(self.pick(['list', 'tuple', 'set']), d)
        if c == 9:
            return '%s.replace(%s, %s)' % (e(), self.pick(STR_LITS), self.pick(STR_LITS))
        if c == 10:
            if self.chance(0.4):
                return self.e_fmt(d)
            return '%s[::%s]' % (e(), self.pick(['-1', '2', '-2', '3', self.expr('int', 0)]))
        if c == 11:
            return self.idx(e(), 'str', d)
        if c == 12:
            return 'f"{%s}-{%s!r}"' % (self.expr('num', 0), self.pick([v for v in self.vars_of('str')] + ["'abc'", "'x'"]))
        if c == 13:
            return 'chr(abs(%s) %% 1000 + 32)' % self.expr('int', d)
        if c == 14:
            return 'type(%s).__name__' % self.expr('any', d)
        return self.call_expr('str', d)

    def e_bytes(self, d):
        e = lambda k='bytes': self.expr(k, d)
        c = self.r.randint(0, 5)
        if c == 0:
            self.grow = True
            return '(%s + %s)' % (e(), e())
        if c == 1:
            return '%s[%s:%s]' % (e(), self.slice_bound(d), self.slice_bound(d))
        if c == 2:
            return '%s.encode()' % self.expr('str', d)
        if c == 3:
            return 'bytes(%s %% 256 for x in range(%d))' % (self.pick(['x', 'x * 7', '-x']), self.r.randint(0, 5))
        if c == 4:
            return '%s.upper()' % e()
        self.grow = True
        return '(%s * %s)' % (e(), self.pick(SMALL))

    def slice_bound(self, d):
        return self.pick(['', '', '1', '-1', '2', '-2', '0', self.expr('int', 0), '2**63'])

    def e_list(self, d):
        e = lambda k='list': self.expr(k, d)
        c = self.r.randint(0, 13)
        if c == 0:
            return '[%s]' % ', '.join(self.expr('num', d) for _ in range(self.r.randint(0, 3)))
        if c == 1:
            return 'list(range(%d, %d))' % (self.r.randint(-3, 2), self.r.randint(0, 6))
        if c == 2:
            return self.comp('list', 'num', d, '[]')
        if c == 3:
            return 'sorted(%s%s)' % (self.expr(self.pick(['list', 'tuple', 'set']), d),
                                     self.pick(['', ', reverse=True', ', key=abs', ', key=lambda q: -q']))
        if c == 4:
            self.grow = True
            return '(%s + %s)' % (e(), e())
        if c == 5:
            if self.chance(0.3):
                return '%s[%s:%s:%s]' % (e(), self.slice_bound(d), self.slice_bound(d),
                                         self.pick(['-1', '2', '-3', self.expr('int', 0)]))
            return '%s[%s:%s]' % (e(), self.slice_bound(d), self.slice_bound(d))
        if c == 6:
            return 'list(%s)' % self.expr(self.pick(['tuple', 'set']), d)
        if c == 7:
            return 'list(reversed(%s))' % e()
        if c == 8:
            return 'list(%s.values())' % self.expr('dict', d)
        if c == 9:
            return '[%s, *%s]' % (self.expr('num', d), self.expr(self.pick(['list', 'tuple']), d))
        if c == 10:
            if self.classes and self.chance(0.5):
                return 'list(%s)' % self.expr('obj', d)
            return 'list(map(abs, %s))' % e()
        if c == 11:
            return '[i * %s for i, _ in enumerate(%s)]' % (self.pick(NUM_LITS), self.expr(self.pick(SEQS), d))
        if c == 12 and self.gens():
            g = self.pick(self.gens())
            return 'list(%s)' % self.call_of(g, d)
        return '[a - b for a, b in zip(%s, %s)]' % (e(), self.expr('tuple', d))

    def e_tuple(self, d):
        e = lambda k='tuple': self.expr(k, d)
        c = self.r.randint(0, 7)
        if c == 0:
            n = self.r.randint(0, 3)
            return '(%s%s)' % (', '.join(self.expr('num', d) for _ in range(n)), ',' if n == 1 else '')
        if c == 1:
            return 'tuple(%s)' % self.expr(self.pick(['list', 'set']), d)
        if c == 2:
            self.grow = True
            return '(%s + %s)' % (e(), e())
        if c == 3:
            return '%s[%s:%s]' % (e(), self.slice_bound(d), self.slice_bound(d))
        if c == 4:
            return 'divmod(%s, %s)' % (self.expr('num', d), self.expr('num', d))
        if c == 5:
            return 'tuple(%s)' % self.comp('tuple', 'num', d, '()')
        if c == 6:
            return '(*%s, %s)' % (self.expr('list', d), self.expr('num', d))
        return 'tuple(sorted(%s))' % self.expr('set', d)

    def e_set(self, d):
        e = lambda k='set': self.expr(k, d)
        c = self.r.randint(0, 4)
        if c == 0:
            return '{%s}' % ', '.join(self.expr('int', d) for _ in range(self.r.randint(1, 3)))
        if c == 1:
            return 'set(%s)' % self.expr(self.pick(['list', 'tuple']), d)
        if c == 2:
            return '(%s %s %s)' % (e(), self.pick(['|', '&', '-', '^']), e())
        if c == 3:
            return self.comp('set', 'num', d, '{}')
        return 'set(range(%d))' % self.r.randint(0, 5)

    def e_dict(self, d):
        e = lambda k='dict': self.expr(k, d)
        c = self.r.randint(0, 5)
        if c == 0:
            return '{%s}' % ', '.join('%s: %s' % (k, self.expr('num', d))
                                      for k in self.r.sample(KEYS, self.r.randint(0, 3)))
        if c == 1:
            return self.comp('dict', 'num', d, '{:}')
        if c == 2:
            return 'dict(zip((%s), %s))' % (', '.join(KEYS[:3]), self.expr('list', d))
        if c == 3:
            return '{**%s, %s: %s}' % (e(), self.pick(KEYS), self.expr('num', d))
        if c == 4:
            return 'dict(%s, k2=%s)' % (e(), self.expr('num', d))
        return '%s.copy()' % e()

    def e_obj(self, d):
        if not self.classes:
            return self.lit('obj')
        c = self.r.randint(0, 2)
        if c == 0:
            return self.lit('obj') if self.chance(0.6) else '%s.make(%s)' % (
                self.pick(self.classes)[0], self.expr('num', d))
        if c == 1:
            return '(%s + %s)' % (self.expr('obj', d), self.expr('num', d))
        cls = self.pick(self.classes)[0]
        return '%s(%s, %s)' % (cls, self.expr('num', d), self.expr('num', d))

    def cond(self, d):
        e = lambda k='num': self.expr(k, d)
        c = self.r.randint(0, 13)
        if c < 3:
            return '%s %s %s' % (e(), self.pick(['<', '<=', '==', '!=', '>', '>=']), e())
        if c == 3:
            return '%s < %s <= %s' % (e(), e(), e())
        if c == 4:
            return '%s in %s' % (e(), self.expr(self.pick(['list', 'tuple', 'set']), d))
        if c == 5:
            return '%s in %s' % (self.pick(KEYS), self.expr('dict', d))
        if c == 6:
            return 'not (%s)' % self.cond(d - 1)
        if c == 7:
            return '(%s) %s (%s)' % (self.cond(d - 1), self.pick(['and', 'or']), self.cond(d - 1))
        if c == 8:
            return 'isinstance(%s, %s)' % (self.expr('any', d), self.pick(list(ISINST.values()) + ['bool', 'float']))
        if c == 9:
            return 'bool(%s)' % self.expr(self.pick(SEQS + ('dict', 'set')), d)
        if c == 10:
            return '%s(%s)' % (self.pick(['any', 'all']), self.comp('list', 'num', d, '()'))
        if c == 11 and self.classes:
            if self.chance(0.3):
                return '%s in %s' % (self.expr('num', d), self.expr('obj', d))
            return '%s %s %s' % (self.expr('obj', d), self.pick(['==', '!=', '<']), self.expr('obj', d))
        if c == 12:
            return '%s.startswith(%s)' % (self.expr('str', d), self.pick(STR_LITS))
        if self.chance(0.3):
            x = self.expr(self.pick(['num', 'int', 'any']), d)
            return '%s %s %s' % (x, self.pick(['<', '<=', '==', '!=', '>', '>=']), x)
        return e()

    # ---- calls of the program's functions -----------------------------

    def gens(self):
        return [f for f in self.funcs if f.gen]

    def args_for(self, f, value):
        """arguments for a call of f, in some style: (tag, text) pairs,
        tag 'pos', 'name' or 'star2'; value(kind) makes each value"""
        parts = []
        by_name = self.chance(0.25)
        for name, kind, default, kwonly in f.params:
            if name == 'args':
                if not by_name:
                    parts += [('pos', value('num')) for _ in range(self.r.randint(0, 2))]
                continue
            if name == 'kw':
                if self.chance(0.5):
                    parts.append(('star2', "{'z%d': %s}" % (self.r.randint(1, 2), value('num'))))
                continue
            if default is not None and self.chance(0.3):
                by_name = by_name or not kwonly   # later ones by name
                continue
            v = value(kind)
            parts.append(('name', (name, v)) if by_name or kwonly else ('pos', v))
        return parts

    def call_of(self, f, d):
        parts = self.args_for(f, lambda k: self.expr(k, d))
        pos = [t for tag, t in parts if tag == 'pos']
        out = []
        if pos and self.chance(0.3):
            out.append(self.pick(['*(%s,)', '*[%s]']) % ', '.join(pos))
        else:
            out += pos
        out += ['%s=%s' % t for tag, t in parts if tag == 'name']
        out += ['**' + t for tag, t in parts if tag == 'star2']
        return '%s(%s)' % (f.name, ', '.join(out))

    def call_expr(self, kind, d):
        fs = [f for f in self.funcs if f.ret == kind and not f.gen]
        if not fs or d <= 0:
            return self.lit(kind)
        return self.call_of(self.pick(fs), d - 1)

