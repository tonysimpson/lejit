    def store(self, ind, kind, d=3, name=None, in_loop=False):
        """assign an expression of kind to a new or existing variable"""
        self.grow = False
        e = self.expr(kind, d)
        if name is None:
            olds = [v for v, k in self.scope.items() if k == kind and v not in self.frozen
                    and v.startswith('v')]
            if olds and self.chance(0.4):
                name = self.pick(olds)
            else:
                name = self.fresh()
        old = name in self.scope
        if kind in SEQS and (self.grow or (old and in_loop)):
            e = '(%s)[%s]' % (e, self.pick([':6', ':12', '-8:']))
        elif kind == 'num' and old and in_loop:
            e = '(%s) %% %s' % (e, self.pick(['97', '2**31', '2**63+1', '1000003', '2.5']))
        elif kind == 'int' and old and in_loop:
            e = '(%s) %% %s' % (e, self.pick(['97', '2**31', '2**63+1', '1000003', '-7']))
        if old and self.chance(0.3) and kind in ('num', 'int', 'str', 'list', 'tuple') and not in_loop:
            op = '+='
            if kind in ('num', 'int'):
                op = self.pick(['+=', '-=', '*=', '//=', '%=', '|=', '&='] if kind == 'int' else ['+=', '-=', '/=', '*='])
            if op == '*=':
                e = self.pick(NUM_LITS)
            elif kind in SEQS and op == '+=':
                e = self.lit(kind)
            self.emit(ind, '%s %s %s' % (name, op, e))
            if kind == 'int' and op not in ('//=', '%=', '|=', '&=', '+=', '-='):
                pass
            if kind == 'int' and op in ('/=',):
                self.scope[name] = 'num'
        else:
            self.emit(ind, '%s = %s' % (name, e))
        if not old or self.scope.get(name) == kind:
            self.scope[name] = kind
        return name

    def block(self, ind, n, depth, in_loop=False):
        saved = dict(self.scope)
        start = len(self.lines)
        for _ in range(n):
            self.stmt(ind, depth, in_loop)
        if len(self.lines) == start:
            self.emit(ind, 'pass')
        # names first bound in the block may be unbound after it
        self.scope = {v: k for v, k in self.scope.items() if v in saved}
        for v in saved:
            self.scope[v] = saved[v]

