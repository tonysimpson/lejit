"""Shared parts of the slot generators (gen_long.py, gen_float.py): C
statements, macro expansion, the slot table, and the driver that writes a
generated header's report (generate.py runs them)."""
import collections
import os

import ctokens
import cpython_src

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# What a generator is given: the CPython source tree, its version, and the
# interpreter being built for with its installed pyconfig.h.
Target = collections.namedtuple('Target', 'src version python pyconfig')


class GenError(Exception):
    """The source doesn't match what a generator relies on: stop the build."""


class Skip(Exception):
    """This slot doesn't have a shape the generator knows."""


def text(toks):
    """Tokens back to C, with the source's own spacing."""
    return ''.join((' ' if t.sp and k else '') + t.text
                   for k, t in enumerate(toks))


def is_seq(toks, words):
    return [t.text for t in toks] == words.split()


def statements(toks):
    """Split a body into statements: 'x;', 'if (...) S', '{...}'."""
    out, i = [], 0
    while i < len(toks):
        t = toks[i]
        if t.text == '{':
            j = ctokens.match_close(toks, i)
            out.append(toks[i:j + 1])
            i = j + 1
        else:
            k = _stmt_end(toks, i)
            out.append(toks[i:k + 1])
            i = k + 1
    return out


def _stmt_end(toks, i):
    if toks[i].text == '{':
        return ctokens.match_close(toks, i)
    if toks[i].text == 'if':
        k = _stmt_end(toks, ctokens.match_close(toks, i + 1) + 1)
        if k + 1 < len(toks) and toks[k + 1].text == 'else':
            k = _stmt_end(toks, k + 2)
        return k
    depth = 0
    for j in range(i, len(toks)):
        if toks[j].text in '([{':
            depth += 1
        elif toks[j].text in ')]}':
            depth -= 1
        elif toks[j].text == ';' and depth == 0:
            return j
    raise Skip('statement without ;')


def expand(stmt, macros):
    """Expand a statement that is one call of a function-like macro, and
    unwrap do { ... } while (0)."""
    if (len(stmt) >= 4 and stmt[0].text in macros and stmt[1].text == '('
            and macros[stmt[0].text].params is not None):
        m = macros[stmt[0].text]
        close = ctokens.match_close(stmt, 1)
        args = ctokens.split_top(stmt[2:close], ',')
        if len(args) != len(m.params) or stmt[close + 1:] != stmt[-1:]:
            return [stmt]
        env = dict(zip(m.params, args))
        body = []
        for t in m.body:
            body.extend(env.get(t.text, [t]) if t.kind == 'id' else [t])
        if (body and body[0].text == 'do'
                and is_seq(body[-4:], 'while ( 0 )')):
            body = body[2:-5]
        return statements(body)
    return [stmt]


def number_methods(src):
    """PyNumberMethods' field names, from whichever Include/**/*.h declares
    it (object.h until 3.7, cpython/object.h from 3.8)."""
    paths = []
    for d, _, files in os.walk(os.path.join(src, 'Include')):
        paths += [os.path.join(d, f) for f in files if f.endswith('.h')]
    first = os.path.join(src, 'Include', 'object.h')
    for p in [first] + sorted(set(paths) - {first}):
        with open(p) as f:
            try:
                return ctokens.struct_fields(ctokens.tokenize(f.read())[0],
                                             'PyNumberMethods')
            except LookupError:
                continue
    raise LookupError('no struct PyNumberMethods in Include/')


def generate(src, cfile, table_name, tool, includer, provides, init_name,
             translate, head):
    """Try translate(cname, slot, params, body, macros) on every slot in
    table_name; return (header text, done, skipped)."""
    with open(os.path.join(src, 'Objects', cfile)) as f:
        toks, macros = ctokens.tokenize(f.read(), cfile)
    fields = number_methods(src)
    funcs = ctokens.functions(toks)
    table = ctokens.initializer(toks, table_name)
    done, skipped, seen = [], [], set()
    for slot, cname in zip(fields, table):
        if cname == '0':
            continue
        if cname not in funcs:
            skipped.append((slot, cname, 'no definition found'))
            continue
        try:
            code = translate(cname, slot, funcs[cname][0], funcs[cname][1],
                             macros)
        except Skip as e:
            skipped.append((slot, cname, str(e)))
            continue
        done.append((slot, cname, code if cname not in seen else None))
        seen.add(cname)
    out = ['/* GENERATED by tools/metac/%s from CPython %s\'s'
           % (tool, cpython_src.source_version(src)),
           '   Objects/%s: do not edit. Included by %s,' % (cfile, includer),
           '   which provides %s. */' % provides, '']
    out += head + ['']
    out += [code + '\n' for _, _, code in done if code is not None]
    out += ['static void %s(PyNumberMethods *m) {' % init_name]
    out += ['  Psyco_DefineMeta(m->%s, p%s);' % (slot, c) for slot, c, _ in done]
    out += ['}', '']
    out += ['/* not generated:'] + ['   %s (%s): %s' % x for x in skipped]
    out += ['*/', '']
    return '\n'.join(out), done, skipped


def report(done, skipped):
    return (['generated  %-15s %s' % (slot, cname) for slot, cname, _ in done] +
            ['skipped    %-15s %-20s %s' % x for x in skipped])
