"""What Ni was generated from, for ni.build_info (ni/ni.c:build_info):
written as ni_buildinfo_gen.h, string macros and the list of features.

Informational only: nothing checks these values. The header is written by
generate.py on every run and is not part of the generation cache's keys,
so a new Ni commit doesn't invalidate the cache.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
HEADER = 'ni_buildinfo_gen.h'


def _git(cwd, *args):
    try:
        r = subprocess.run(('git',) + args, cwd=cwd, stdout=subprocess.PIPE,
                           stderr=subprocess.DEVNULL, timeout=60,
                           universal_newlines=True)
    except (OSError, subprocess.SubprocessError):
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def ni_commit():
    """Ni's HEAD, with '-dirty' if the tree has uncommitted changes."""
    head = _git(ROOT, 'rev-parse', 'HEAD')
    if not head:
        return 'unknown'
    return head + ('-dirty' if _git(ROOT, 'status', '--porcelain') else '')


def source_origin(src, version, sha):
    """(origin, sha256 or '', git commit or ''): the release tarball's name
    for a tree unpacked from one, else the tree's path, and its commit if
    the tree is a git checkout of its own."""
    if sha != 'local':
        return 'Python-%s.tgz' % version, sha, ''
    commit = ''
    top = _git(src, 'rev-parse', '--show-toplevel')
    if top and os.path.realpath(top) == os.path.realpath(src):
        commit = _git(src, 'rev-parse', 'HEAD') or ''
        if commit and _git(src, 'status', '--porcelain', '--untracked-files=no'):
            commit += '-dirty'
    return src, '', commit


def target_sys_version(python):
    r = subprocess.run([python, '-I', '-c', 'import sys; print(sys.version)'],
                       stdout=subprocess.PIPE, universal_newlines=True,
                       timeout=60)
    return r.stdout.strip() if r.returncode == 0 else 'unknown'


def _c(s):
    """A C string literal (JSON's escapes are C's for these)."""
    return json.dumps(s, ensure_ascii=True)


def build(target, sha, features):
    """The header's text; `features` is features.detect's list."""
    origin, tar_sha, commit = source_origin(target.src, target.version, sha)
    values = [('SOURCE_VERSION', target.version),
              ('SOURCE', origin),
              ('SOURCE_SHA256', tar_sha),
              ('SOURCE_GIT_COMMIT', commit),
              ('PYTHON', target_sys_version(target.python)),
              ('GENERATOR_PYTHON', sys.version),
              ('NI_COMMIT', ni_commit())]
    lines = ['/* Generated by tools/metac/buildinfo.py: do not edit. */',
             '#ifndef NI_BUILDINFO_GEN_H', '#define NI_BUILDINFO_GEN_H',
             '#include "ni_features_gen.h"', '']
    lines += ['#define NI_BUILDINFO_%s %s' % (k, _c(v)) for k, v in values]
    lines += ['', '#define NI_BUILDINFO_FEATURES(F) \\']
    lines += ['  F(%s) \\' % name for name, _, _, _ in features]
    lines += ['', '#endif /* NI_BUILDINFO_GEN_H */', '']
    return '\n'.join(lines)
